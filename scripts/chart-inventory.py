"""Write docs/19-chart-inventory.md from the live chart registry, titles,
axis/colour guides and metric glossary (so the inventory cannot drift)."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'workbench'))
from sandbox.chart_registry import INVENTORY, CHART_META, GROUPS  # noqa: E402
from sandbox.easy import GUIDE  # noqa: E402
from sandbox.interpret import WHAT  # noqa: E402
from sandbox.registry import METRICS, MODELS  # noqa: E402

groups = {g: t for g, t, _ in GROUPS}
out = ['# Research chart inventory', '',
       'Generated by `scripts/chart-inventory.py` from `workbench/sandbox/chart_registry.py`, `easy.py`, `interpret.py` and '
       '`registry.py`. Data sources and calculations are the `implementation` column (functions in `workbench/sandbox/`).', '',
       f'{len(INVENTORY)} charts. Provenance: *current run* = your selected explanation; *requested sweep* = the extra model x concept x '
       'size runs on your data; *published* = paper figure, never your result.', '']
for item in INVENTORY:
    i, meta, guide = item['id'], CHART_META.get(item['id'], {}), GUIDE.get(item['id'], {})
    metric = METRICS.get(meta.get('metric')) if meta.get('metric') else None
    prov = 'published' if item['kind'] == 'blocked' or (item['kind'] == 'static' and i != 'workflow') else meta.get('provenance', 'current run')
    out += [f"## {meta.get('title', i)}", '',
            f"| | |\n|---|---|\n| ID / paper | `{i}` · {item['paper']} |\n| Group | {groups.get(item['group'])} |\n"
            f"| Research question | {item['question']} |\n| Purpose | {WHAT.get(i, '')} |\n| Implementation | `{item['implementation']}` |\n"
            f"| Needs | {item['requires']} |\n| Horizontal axis | {guide.get('x', '')} |\n| Vertical axis | {guide.get('y', '')} |\n"
            f"| Colours | {'; '.join(m for _, m in guide.get('colors', [])) or 'none'} |\n"
            f"| Metric | {metric['name'] + ' (' + metric['unit'] + '; higher is ' + metric['better'] + ')' if metric else 'none (structural view)'} |\n"
            f"| Provenance | {prov} ({item['kind']}) |\n| Reader should understand | {guide.get('shows', '')} |\n"
            f"| Does not support | see the chart's generated 'What not to conclude'; never causal, never a cross-model ranking |" + '', '']
out += ['## Models (display names)', '', '| Technical id | Display name | Reads | Calculates |', '|---|---|---|---|']
out += [f"| `{k}` ({m['technical']}) | {m['name']} | {m['reads']} | {m['calculates']} |" for k, m in MODELS.items()]
out += ['', '## Notes', '',
        '* The paper source is not in this repository (no `paper/` directory); definitions follow the implementation and '
        '`docs/16-guided-user-study.md`. Published figures are in `workbench/publication/`.', '']
(ROOT/'docs'/'19-chart-inventory.md').write_text('\n'.join(out), encoding='utf-8')
print('wrote', len(INVENTORY), 'charts')
